#!/usr/bin/env python3
"""Render the compatibility Dockerfile or pinned fleet ImageLayer definitions.

No registry, forge CI, or third-party Python dependencies are required.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STAGES = {'base': 0, 'utilities': 1, 'project': 2, 'capability': 3, 'harness': 4}
INPUTS = ROOT / '.flotilla/image-layers/inputs.json'
AUDIT = ROOT / 'ci/crew-image/link-audit.sh'


def order(layer):
    return (bool(layer.get('link')), 0 if layer.get('link') else STAGES[layer['stage']], layer['name'])


def validate_link(layer):
    name = layer['name']
    link = layer['link']
    if not re.fullmatch(r'[A-Za-z0-9_.-]+', name) or name in ['.', '..'] or not link['builder_image'] or re.search(r'\s', link['builder_image']):
        raise ValueError('invalid link layer name or builder image')
    tree = '/opt/flotilla/layers/' + name + '/'
    if tree not in link['outputs']:
        raise ValueError('link layer must export its private tree')
    for path in link['outputs']:
        binary = path.removeprefix('/opt/flotilla/bin/')
        valid_bin = path.startswith('/opt/flotilla/bin/') and re.fullmatch(r'[A-Za-z0-9_.-]+', binary) and binary not in ['.', '..']
        valid_prelude = re.fullmatch(r'/etc/flotilla/prelude.d/[0-9]{2}-' + re.escape(name) + r'\.sh', path)
        if path != tree and not valid_bin and not valid_prelude:
            raise ValueError('link layer writes outside allowed paths: ' + path)


def producer(layer, fragment):
    validate_link(layer)
    link = layer['link']
    outputs = ''.join(" '" + path + "'" for path in sorted(link['outputs']))
    return ('ARG BUILDER\nFROM ' + link['builder_image'] + ' AS flotilla-link-producer\n' + fragment +
            '\nFROM ' + link['builder_image'] + ' AS flotilla-link-audit\nCOPY --from=flotilla-link-producer /out/ /out/\n' + "USER 0:0\nRUN <<'FLOTILLA_LINK_AUDIT'\nunset FLOTILLA_LINK_OUTPUT_ROOT\nset -- '" + layer['name'] + "'" + outputs + '\n' +
            AUDIT.read_text() + '\nFLOTILLA_LINK_AUDIT\nFROM scratch\n' +
            'COPY --from=flotilla-link-audit --chown=0:0 /out/ /\n')


def splice_paths(layer):
    paths = ['/opt/flotilla/layers/' + layer['name'] + '/']
    for prefix in ['/opt/flotilla/bin/', '/etc/flotilla/prelude.d/']:
        if any(path.startswith(prefix) for path in layer['link']['outputs']):
            paths.append(prefix)
    return paths


def dockerfile(display=False, formal_modelling=False):
    catalogue = json.loads(INPUTS.read_text())
    parent = catalogue['base_default']
    parts = ['# Generated by ci/crew-image/compose.py; edit image-layers fragments.\n']
    exported = set()
    selected = {'capability-display-x11': display,
                'capability-formal-modelling': formal_modelling}
    for layer in sorted(catalogue['layers'], key=order):
        if layer['stage'] == 'capability' and not selected.get(layer['name'], False):
            continue
        fragment = (ROOT / layer['fragment']).read_text()
        if layer.get('link'):
            # A compatibility Dockerfile uses named producer stages; production
            # splices use realised immutable image identities from ImageBuild.
            paths = set(layer['link']['outputs'])
            if exported & paths:
                raise ValueError('link layers collide on output paths')
            exported.update(paths)
            fragment = producer(layer, fragment)
            fragment = fragment.replace(' AS flotilla-link-producer', ' AS producer-' + layer['name'])
            fragment = fragment.replace('--from=flotilla-link-producer', '--from=producer-' + layer['name'])
            fragment = fragment.replace(' AS flotilla-link-audit', ' AS audit-' + layer['name'])
            fragment = fragment.replace('--from=flotilla-link-audit', '--from=audit-' + layer['name'])
            lines = fragment.splitlines()
            lines[lines.index('FROM scratch')] += ' AS output-' + layer['name']
            parts.append('\n'.join(lines) + '\n')
            fragment = 'FROM ' + parent + '\n' + ''.join(
                'COPY --link --from=output-' + layer['name'] + ' --chown=0:0 ' + path + ' ' + path + '\n'
                for path in splice_paths(layer))
        # Substitute the parent only in FROM instructions. Preserve ARGs and
        # helpers: each fragment is also independently buildable by Buildx.
        fragment = re.sub(r'(?m)^FROM \$\{BASE\}(.*)$',
                          lambda m: 'FROM ' + parent + m[1], fragment)
        lines = fragment.splitlines()
        last = max(i for i, line in enumerate(lines) if line.startswith('FROM '))
        lines[last] += ' AS ' + layer['name']
        parts.append('\n'.join(lines) + '\n')
        parent = layer['name']
    return '\n'.join(parts)


def manifests(revision, base):
    if not re.fullmatch(r'[0-9a-f]{40}|[0-9a-f]{64}', revision):
        raise ValueError('revision must be a full lowercase commit ID')
    if not re.fullmatch(r'.*@sha256:[0-9a-f]{64}|sha256:[0-9a-f]{64}', base):
        raise ValueError('base must be a resolved sha256 image digest')
    catalogue = json.loads(INPUTS.read_text())
    rust = re.search(r'^channel = \"([0-9.]+)\"$', (ROOT / 'rust-toolchain.toml').read_text(), re.M).group(1)
    records = []
    for layer in sorted(catalogue['layers'], key=order):
        stage = layer['stage']
        if layer.get('link'):
            validate_link(layer)
        if stage == 'base':
            provide = 'toolchain:rust@' + rust
            layer.setdefault('provides', []).append(provide)
            layer.setdefault('probes', {})[provide] = ['sh', '-c', 'test \"$(rustc --version | cut -d \" \" -f2)\" = ' + rust]
        parent = ({'kind': 'image', 'value': base} if stage == 'base' else
                  {'kind': 'layer', 'value': 'spine-base'} if stage == 'utilities' else
                  {'kind': 'rebasable'})
        records.append({'apiVersion': 'flotilla.work/v1', 'kind': 'ImageLayer',
                        'metadata': {'namespace': 'flotilla', 'name': layer['name']},
                        'spec': {'stage': stage, 'parent': parent,
                                 **({'link': layer['link']} if layer.get('link') else {}),
                                 'repository': catalogue['repository'], 'revision': revision,
                                 'fragment': layer['fragment'], 'pins': layer.get('pins', {}),
                                 'provides': layer.get('provides', []),
                                 'requires': layer.get('requires', []),
                                 'probes': layer.get('probes', {}),
                                 'input_stability': catalogue['input_stability']}})
    # JSON documents are valid YAML; the operational loader accepts documents.
    return '\n---\n'.join(json.dumps(record, indent=2) for record in records) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--display', action='store_true')
    parser.add_argument('--formal-modelling', action='store_true')
    parser.add_argument('--revision')
    parser.add_argument('--base')
    args = parser.parse_args()
    if args.revision or args.base:
        if not (args.revision and args.base):
            parser.error('--revision and --base are required together')
        print(manifests(args.revision, args.base), end='')
    else:
        print(dockerfile(args.display, args.formal_modelling), end='')
