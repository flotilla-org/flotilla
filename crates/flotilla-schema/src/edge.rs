//! Edge writes: the event-driven write path (#3320 ruling 1).
//!
//! A machine's state is a value, its label plus its data (#3319 ruling of 2026-10-15), and every
//! edge writes it: a state-machine edge is one write that sets the kind's `#[store(state)]` field
//! to the new state value, logs its [`EdgeEvent`] as the header and payload of the write's entry
//! in the store's per-home `log` (#3392 G8), and may set other fields it declares (root columns,
//! or fields of one existing `records` row) and append declared `records` or `history` rows. [`Edge`] describes such a write without a
//! backend: it encodes each named field through the field's own adapter into
//! logical values, and each appended row through its `Element` codec. A backend resolves the
//! tables, takes the next positions and stamps every appended row with the write's sequence.
//!
//! The derive generates the typed handles an edge names: for each field of a struct deriving
//! `Stored` (a kind or a part), an associated const named by the field in upper case:
//! `Message::STATE: StateOf<Message, State<MessageState>>` for a `state` field,
//! `Message::SUBJECT: ColumnOf<Message, Option<MessageReference>>` for another column-shaped field,
//! `Session::RECEIPTS: HistoryOf<Session, Receipt>` for a `history` field and
//! `Convoy::DELIVERABLES: RecordsOf<Convoy, Deliverable>` for a `records` field. Spec collections
//! (`child`) have no handle: they change only by a spec edit.
//!
//! Nesting is one `records` level deep: [`Edge::set_in`] and [`Edge::append_in`] address a row of
//! a `records` table of the kind itself (a deliverable) and a field or table of that row (its
//! state, its evidence). The rows they address must exist before the edge.
//!
//! A state carrying data (a label-plus-data enum, `#[store(labels = L)]`) moves through
//! [`Edge::transition`], which takes the previous and the next state value (#3373 ruling 2): it
//! writes the label and its `since` only when the label changes, each column datum only when its
//! columns differ, and each collection datum row by row (an insert per new key, an update per
//! changed value, a delete per removed key), never the whole collection. Data a label change leaves
//! behind is nulled, or its rows deleted. Every edge also names the label it leaves (`from`), which
//! the backend checks against the stored label inside the write (#3373 ruling 5).

use std::{collections::BTreeMap, fmt, marker::PhantomData};

use crate::{
    codec::{EncodeError, Encoder},
    descriptor::TableRole,
    history::{EdgeEvent, Labelled},
    inline::{Cbor, INLINE_LIMITS},
    records::Position,
    state::{RowEdit, State, StateDelta},
    time::Timestamp,
    traits::{CodeEnum, Element, StateData},
    value::{Hash, Identity, Rows, Value},
};

/// A column-shaped field `F` of rows of `O` (a kind or a part): what [`Edge::set`] and
/// [`Edge::set_in`] write. Generated by the derive; `encode` is the field's adapter.
pub struct ColumnOf<O, F> {
    name: &'static str,
    tables: usize,
    encode: fn(&F, &mut Encoder) -> Result<(), EncodeError>,
    owner: PhantomData<fn() -> O>,
}

impl<O, F> ColumnOf<O, F> {
    /// `tables` is the number of nested tables the field declares: a field holding a table (a
    /// data enum with a `child` variant) cannot be set by an edge.
    #[doc(hidden)]
    pub const fn new(name: &'static str, tables: usize, encode: fn(&F, &mut Encoder) -> Result<(), EncodeError>) -> ColumnOf<O, F> {
        ColumnOf { name, tables, encode, owner: PhantomData }
    }

    pub fn name(&self) -> &'static str {
        self.name
    }
}

/// The `#[store(state)]` field of rows of `O`, holding the state value `S`: what
/// [`Edge::transition`] and [`Edge::new`] write, and [`Edge::set_in`] on a `records` row.
pub struct StateOf<O, S> {
    column: ColumnOf<O, S>,
    /// The state value's data names: empty for a code enum.
    data: &'static [&'static str],
}

impl<O, S> StateOf<O, S> {
    #[doc(hidden)]
    pub const fn new(column: ColumnOf<O, S>, data: &'static [&'static str]) -> StateOf<O, S> {
        StateOf { column, data }
    }

    pub fn name(&self) -> &'static str {
        self.column.name
    }
}

impl<O, S> Clone for StateOf<O, S> {
    fn clone(&self) -> StateOf<O, S> {
        *self
    }
}

impl<O, S> Copy for StateOf<O, S> {}

impl<O, S> fmt::Debug for StateOf<O, S> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "StateOf({})", self.column.name)
    }
}

/// A column-shaped field `F` of rows of `O` an edge may set inside a `records` row: a
/// [`ColumnOf`] or a [`StateOf`].
pub trait FieldOf<O, F>: Copy {
    fn column(self) -> ColumnOf<O, F>;

    /// A state field whose value carries data, which only [`Edge::transition`] writes.
    fn carries_data(self) -> bool {
        false
    }
}

impl<O, F> FieldOf<O, F> for ColumnOf<O, F> {
    fn column(self) -> ColumnOf<O, F> {
        self
    }
}

impl<O, F> FieldOf<O, F> for StateOf<O, F> {
    fn column(self) -> ColumnOf<O, F> {
        self.column
    }

    fn carries_data(self) -> bool {
        !self.data.is_empty()
    }
}

/// A `records` field of rows of `O`, holding rows of `R`.
pub struct RecordsOf<O, R> {
    name: &'static str,
    owner: PhantomData<fn() -> (O, R)>,
}

/// A `history` field of rows of `O`, holding rows of `R`.
pub struct HistoryOf<O, R> {
    name: &'static str,
    owner: PhantomData<fn() -> (O, R)>,
}

macro_rules! table_handle {
    ($handle:ident, $role:expr) => {
        impl<O, R> $handle<O, R> {
            #[doc(hidden)]
            pub const fn new(name: &'static str) -> $handle<O, R> {
                $handle { name, owner: PhantomData }
            }
        }

        impl<O, R> AppendTo<O, R> for $handle<O, R> {
            const ROLE: TableRole = $role;

            fn name(&self) -> &'static str {
                self.name
            }
        }

        impl<O, R> Clone for $handle<O, R> {
            fn clone(&self) -> $handle<O, R> {
                *self
            }
        }

        impl<O, R> Copy for $handle<O, R> {}

        impl<O, R> fmt::Debug for $handle<O, R> {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                write!(f, "{}({})", stringify!($handle), self.name)
            }
        }
    };
}

table_handle!(RecordsOf, TableRole::Records);
table_handle!(HistoryOf, TableRole::History);

impl<O, F> Clone for ColumnOf<O, F> {
    fn clone(&self) -> ColumnOf<O, F> {
        *self
    }
}

impl<O, F> Copy for ColumnOf<O, F> {}

impl<O, F> fmt::Debug for ColumnOf<O, F> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "ColumnOf({})", self.name)
    }
}

/// A table of rows of `O` an edge may append `R` rows to: a `records` or `history` field.
pub trait AppendTo<O, R>: Copy {
    const ROLE: TableRole;
    fn name(&self) -> &'static str;
}

/// The row an edge writes a field of, or appends under.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RowPath {
    /// The kind's own row.
    Root,
    /// The row at `position` of the kind's `records` field `table`.
    Record { table: &'static str, position: Position },
}

/// One field an edge sets: the field's values, in its columns' order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EdgeSet {
    pub row: RowPath,
    pub field: &'static str,
    pub values: Vec<Value>,
}

/// One row an edge appends to the table `table` under `under`, with the rows nested in it.
///
/// `rows` is the appended row's encoding as its own resource: table 0 holds the row (key empty,
/// values led by a placeholder version stamp) and tables `1..` the tables nested in it, in
/// pre-order, keyed relative to the row. The backend prefixes the keys with the row's key and
/// stamps every `records` and `history` row with the write's sequence.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EdgeAppend {
    pub under: RowPath,
    pub table: &'static str,
    pub role: TableRole,
    pub rows: Rows,
}

/// One row an edge inserts, updates or deletes in a table of state data (`TableRole::State`) of
/// the row `under`: `table` names the datum, and the edit's key is the row's own key.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EdgeRow {
    pub under: RowPath,
    pub table: &'static str,
    pub edit: RowEdit,
}

/// The label an edge leaves: the event's `from`, which the backend refuses unless the kind's
/// state field `field` holds it when the edge is applied.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct LabelCheck {
    pub field: &'static str,
    pub code: i64,
}

/// An edge's event as its `log` entry records it: the header columns and the payload's canonical
/// CBOR (#3392 G8). `about` is the edge's master, the resource it is about (G11), when it
/// declares one.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EdgeHeader {
    pub edge: i64,
    pub from: i64,
    pub to: i64,
    pub writer: String,
    pub at: Timestamp,
    pub payload: Vec<u8>,
    pub about: Option<Identity>,
}

impl EdgeHeader {
    /// The payload as the edge wrote it.
    pub fn payload<P: Cbor>(&self) -> Result<P, EdgeError> {
        flotilla_cbor::from_slice(&self.payload, &INLINE_LIMITS).map_err(|error| EdgeError::Payload { kind: error.kind() })
    }
}

/// An edge's writes, as a backend executes them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EdgeParts {
    /// The root's state fields first (its label, then its data), contiguous, then other fields.
    pub sets: Vec<EdgeSet>,
    /// Row edits of the state's collection data: deletes, updates, then inserts, per datum.
    pub rows: Vec<EdgeRow>,
    /// The declared appends, in order.
    pub appends: Vec<EdgeAppend>,
    /// Every object the edge's values name: an edge carries the objects it sets.
    pub objects: BTreeMap<Hash, Vec<u8>>,
    pub from: LabelCheck,
    pub event: EdgeHeader,
}

/// Why an edge could not be built.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum EdgeError {
    #[error(transparent)]
    Encode(#[from] EncodeError),
    /// A field whose value spans a nested table changes only by a spec edit.
    #[error("field {field} holds a table and cannot be set by an edge")]
    Tables { field: String },
    /// One write sets a field once.
    #[error("field {field} is set twice on one row")]
    Repeated { field: String },
    /// The event's `to` label is not the label of the state the edge writes.
    #[error("the event enters label {to}, but the state written to {field} has label {state}")]
    Label { field: String, to: i64, state: i64 },
    /// The event's `from` label is not the label of the previous state.
    #[error("the event leaves label {from}, but the previous state of {field} has label {state}")]
    From { field: String, from: i64, state: i64 },
    /// The next state's `since` is not the time its label was entered: the event's `at` when the
    /// label changes, and the previous `since` when it does not.
    #[error("the state written to {field} has since {found}, not {expected}")]
    Since { field: String, expected: Timestamp, found: Timestamp },
    /// A state carrying data is written by `Edge::transition`, from the previous value.
    #[error("the state of {field} carries data and is written by a transition from the previous value")]
    Data { field: String },
    /// The event's payload is not an inline CBOR document within its bounds.
    #[error("the event payload is not an inline document: {kind:?}")]
    Payload { kind: flotilla_cbor::ErrorKind },
}

/// One edge write to a resource of kind `K`, built from typed handles; see the module docs.
///
/// ```text
/// let next = State::new(TicketState::Closed { .. }, event.at);
/// let event = EdgeEvent { edge: TicketEdge::Close, from: Open, to: Closed, writer, at, payload };
/// let edge = Edge::transition(Ticket::STATE, &previous, &next, &event)?.set(Ticket::TITLE, &title)?;
/// write.apply_edge(current, edge)?;
/// ```
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Edge<K> {
    parts: EdgeParts,
    kind: PhantomData<fn() -> K>,
}

impl<K> Edge<K> {
    /// An edge that moves the kind's `state` from `previous` to `next`, logged as `event` (#3373
    /// rulings 2 and 3, #3392 G8). The event must leave `previous`'s label and
    /// enter `next`'s. When the label changes, the label and its `since` are written, and `next`'s
    /// `since` must be the event's `at`; otherwise neither is written and `next` keeps `previous`'s
    /// `since`. Each datum of the state is written only where it differs: a column datum's columns
    /// when they differ (nulled when `next`'s label lacks it), and a collection datum's rows one at
    /// a time. `previous` must be the state stored at the stamp the edge is applied under: the
    /// backend checks the stored label and version, and derives nothing from the stored data.
    pub fn transition<S: StateData, E: CodeEnum, P: Cbor>(
        state: StateOf<K, State<S>>,
        previous: &State<S>,
        next: &State<S>,
        event: &EdgeEvent<S::Label, E, P>,
    ) -> Result<Edge<K>, EdgeError> {
        let field = state.name();
        let (from, held) = (event.from.code(), previous.value.code());
        if from != held {
            return Err(EdgeError::From { field: field.to_owned(), from, state: held });
        }
        let (to, label) = (event.to.code(), next.value.code());
        if to != label {
            return Err(EdgeError::Label { field: field.to_owned(), to, state: label });
        }
        let moved = held != label;
        let since = if moved { event.at } else { previous.since };
        if next.since != since {
            return Err(EdgeError::Since { field: field.to_owned(), expected: since, found: next.since });
        }
        let mut edge = Edge::empty(field, event)?;
        if moved {
            let values = vec![Value::Int(label), Value::Int(event.at.micros())];
            edge.parts.sets.push(EdgeSet { row: RowPath::Root, field, values });
        }
        let mut delta = StateDelta::default();
        S::delta(&previous.value, &next.value, &mut delta).map_err(|error| error.at(field))?;
        for (datum, values) in delta.sets {
            edge.parts.sets.push(EdgeSet { row: RowPath::Root, field: datum, values });
        }
        edge.parts.rows.extend(delta.rows.into_iter().map(|(table, edit)| EdgeRow { under: RowPath::Root, table, edit }));
        edge.parts.objects.extend(delta.objects);
        Ok(edge)
    }

    /// An edge that writes the kind's `state` as `next`, whatever it held, logged as `event`: for a
    /// state that carries no data (a code enum), whose label and
    /// `since` are its whole value. The event's `to` must be `next`'s label; its `from` is the
    /// writer's, which read the current state for the optimistic stamp the edge is applied under,
    /// and the backend checks it against the stored label. A state carrying data is refused
    /// (`EdgeError::Data`): it moves through [`Edge::transition`].
    pub fn new<S: StateData, E: CodeEnum, P: Cbor>(
        state: StateOf<K, State<S>>,
        next: &State<S>,
        event: &EdgeEvent<S::Label, E, P>,
    ) -> Result<Edge<K>, EdgeError> {
        if state.carries_data() {
            return Err(EdgeError::Data { field: state.name().to_owned() });
        }
        let (to, label) = (event.to.code(), next.label_code());
        if to != label {
            return Err(EdgeError::Label { field: state.name().to_owned(), to, state: label });
        }
        Edge::empty(state.name(), event)?.setting(RowPath::Root, state.column, next)
    }

    fn empty<L: CodeEnum, E: CodeEnum, P: Cbor>(field: &'static str, event: &EdgeEvent<L, E, P>) -> Result<Edge<K>, EdgeError> {
        let payload = flotilla_cbor::to_vec(&event.payload, &INLINE_LIMITS).map_err(|error| EdgeError::Payload { kind: error.kind() })?;
        let header = EdgeHeader {
            edge: event.edge.code(),
            from: event.from.code(),
            to: event.to.code(),
            writer: event.writer.clone(),
            at: event.at,
            payload,
            about: None,
        };
        let parts = EdgeParts {
            sets: Vec::new(),
            rows: Vec::new(),
            appends: Vec::new(),
            objects: BTreeMap::new(),
            from: LabelCheck { field, code: header.from },
            event: header,
        };
        Ok(Edge { parts, kind: PhantomData })
    }

    /// Names the edge's master, the resource it is about (#3392 G11): the entry's `about`, which
    /// that resource's gates read as entries about it.
    pub fn about(mut self, about: Identity) -> Edge<K> {
        self.parts.event.about = Some(about);
        self
    }

    /// Sets the kind's column-shaped `field` (not its state, which [`Edge::new`] sets) to `value`.
    pub fn set<F>(self, field: ColumnOf<K, F>, value: &F) -> Result<Edge<K>, EdgeError> {
        self.setting(RowPath::Root, field, value)
    }

    /// Appends `row` to the kind's `records` or `history` field `table`.
    pub fn append<R: Element, T: AppendTo<K, R>>(self, table: T, row: &R) -> Result<Edge<K>, EdgeError> {
        self.appended(RowPath::Root, table, row)
    }

    /// Sets `field` of the existing row at `position` of the kind's `records` field `records`.
    pub fn set_in<P, F>(
        self,
        records: RecordsOf<K, P>,
        position: Position,
        field: impl FieldOf<P, F>,
        value: &F,
    ) -> Result<Edge<K>, EdgeError> {
        if field.carries_data() {
            return Err(EdgeError::Data { field: field.column().name.to_owned() });
        }
        self.setting(RowPath::Record { table: records.name, position }, field.column(), value)
    }

    /// Appends `row` to `table` of the existing row at `position` of the kind's `records` field
    /// `records` (evidence submitted under a deliverable).
    pub fn append_in<P, R: Element, T: AppendTo<P, R>>(
        self,
        records: RecordsOf<K, P>,
        position: Position,
        table: T,
        row: &R,
    ) -> Result<Edge<K>, EdgeError> {
        self.appended(RowPath::Record { table: records.name, position }, table, row)
    }

    /// The writes, for a backend.
    pub fn into_parts(self) -> EdgeParts {
        self.parts
    }

    fn setting<O, F>(mut self, row: RowPath, field: ColumnOf<O, F>, value: &F) -> Result<Edge<K>, EdgeError> {
        if field.tables != 0 {
            return Err(EdgeError::Tables { field: field.name.to_owned() });
        }
        if self.parts.sets.iter().any(|set| set.row == row && set.field == field.name) {
            return Err(EdgeError::Repeated { field: field.name.to_owned() });
        }
        let mut rows = Encoder::columns(|e| (field.encode)(value, e).map_err(|error| error.at(field.name)))?;
        self.parts.objects.append(&mut rows.objects);
        let values = rows.tables.swap_remove(0).swap_remove(0).values;
        self.parts.sets.push(EdgeSet { row, field: field.name, values });
        Ok(self)
    }

    fn appended<O, R: Element, T: AppendTo<O, R>>(mut self, under: RowPath, table: T, row: &R) -> Result<Edge<K>, EdgeError> {
        let mut rows = Encoder::encode(row).map_err(|error| error.at(table.name()))?;
        // The stamp column leads every records and history row; the backend writes it.
        rows.tables[0][0].values.insert(0, Value::Int(0));
        self.parts.objects.append(&mut rows.objects);
        self.parts.appends.push(EdgeAppend { under, table: table.name(), role: T::ROLE, rows });
        Ok(self)
    }
}
