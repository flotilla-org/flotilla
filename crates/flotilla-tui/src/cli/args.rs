/// Flotilla: TUI dashboard for managing development workspaces
#[derive(Parser)]
#[command(name = "flotilla", version)]
pub struct Cli {
    /// Git repo roots (repeatable; auto-detected from cwd if omitted)
    #[arg(long)]
    pub repo_root: Vec<PathBuf>,

    /// Daemon identity root (config and state use ROOT/config and ROOT/state)
    #[arg(long, conflicts_with_all = ["config_dir", "state_dir"])]
    pub root: Option<PathBuf>,

    /// Config directory (commands that may start a daemon also require --state-dir)
    #[arg(long, conflicts_with = "root")]
    pub config_dir: Option<PathBuf>,

    /// State directory (commands that may start a daemon also require --config-dir)
    #[arg(long, conflicts_with = "root")]
    pub state_dir: Option<PathBuf>,

    /// Socket path (default: ${config_dir}/run/flotilla.sock)
    #[arg(long)]
    pub socket: Option<PathBuf>,

    /// Use a daemon on another host: ssh://[user@]host[:port][/path/to/flotilla]
    /// (default: $FLOTILLA_DAEMON). Never spawns a local daemon; hooks and
    /// daemon lifecycle commands still act on this host.
    #[arg(long, conflicts_with = "socket")]
    pub daemon: Option<String>,

    /// Theme name (catppuccin-mocha, classic)
    #[arg(long)]
    pub theme: Option<String>,

    /// Output as JSON instead of human-readable text
    #[arg(long, global = true)]
    pub json: bool,

    /// Repository context (project member alias or forge slug; inferred inside an observed checkout)
    #[arg(long)]
    pub repo: Option<String>,

    #[command(subcommand)]
    pub command: Option<SubCommand>,
}

// Variants with arguments take an `Args` struct rather than inline fields, so
// clap builds each variant's arguments in its own call. Inline fields share
// one frame per enum, which overflowed Windows' 1 MiB main thread in
// unoptimised builds (#2588).
// Parsed once per process, so the size gap between `Domain` and the other
// variants costs nothing; boxing would only add derefs to every match.
#[allow(clippy::large_enum_variant)]
#[derive(clap::Subcommand)]
pub enum SubCommand {
    /// Run the daemon server
    Daemon(DaemonArgs),
    /// Open the TUI scoped to one View (e.g. `flotilla view convoys/flotilla`).
    ///
    /// Scoped mode shows exactly that View: no tab bar, and the persisted
    /// open-view set is untouched. This is the deep-link entry Presentation
    /// Manager recipes embed (ADR 0013).
    View(ViewArgs),
    /// Print repo list and state
    Status,
    /// Stream daemon events to stdout
    Watch,
    /// Block until one condition leaf becomes true
    Wait(WaitArgs),
    /// Show the daemon's current multi-host routing view
    Topology(TopologyArgs),
    /// Read structured daemon logs from this host or a peer
    Logs(LogsArgs),
    /// Show fleet-wide host health without collapsing independent observations
    Fleet {
        #[command(subcommand)]
        command: Option<FleetSubCommand>,
    },
    /// List convoy vessels and crew sessions
    Ls(LsArgs),
    /// Attach to a running convoy crew session
    Attach(AttachArgs),
    /// Receive agent hook events (called by agent hook systems)
    Hook(HookArgs),
    /// Install or uninstall agent hook configuration
    Hooks {
        #[command(subcommand)]
        command: HooksSubCommand,
    },
    /// Presentation-manager integration
    Pm {
        #[command(subcommand)]
        command: PmSubCommand,
    },
    /// Roll changed standing-convoy declarations at an operator-chosen boundary
    Ensure {
        #[command(subcommand)]
        command: EnsureSubCommand,
    },
    /// Inspect raw daemon resources
    Resource {
        #[command(subcommand)]
        command: ResourceSubCommand,
    },
    /// Inspect manifest document reconciliation
    Manifest {
        #[command(subcommand)]
        command: ManifestSubCommand,
    },
    /// Store and retrieve crew artifacts
    Artifact {
        #[command(subcommand)]
        command: ArtifactSubCommand,
    },
    /// List recent object-scoped events fleet-wide
    Events(EventsArgs),
    // --- Domain nouns (generated by flotilla-commands) ---
    #[command(flatten)]
    Domain(DomainCommand),

    /// Bridge stdio to this host's daemon socket (hidden; run over SSH by `--daemon ssh://...`)
    #[command(hide = true)]
    DaemonBridge,
    /// Generate completions (hidden, called by shell scripts)
    #[command(hide = true)]
    Complete(CompleteArgs),
    /// Output shell completion setup scripts
    Completions(CompletionsArgs),
}

