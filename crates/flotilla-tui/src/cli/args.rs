#[derive(clap::Subcommand)]
pub enum MessageVerb {
    /// Show your own address, supervision chain and reachable crews
    Contacts {
        #[arg(long)]
        crew_id: Option<String>,
        #[arg(long)]
        namespace: Option<String>,
        #[arg(long)]
        convoy: Option<String>,
        #[arg(long)]
        vessel: Option<String>,
        #[arg(long)]
        role: Option<String>,
    },
}

impl MessageNoun {
    pub fn resolve(self) -> std::result::Result<flotilla_commands::Resolved, String> {
        let MessageVerb::Contacts { crew_id, namespace, convoy, vessel, role } = self.verb;
        let context = flotilla_protocol::CrewCommandContext {
            crew_id: crew_id.or_else(|| std::env::var("FLOTILLA_CREW_ID").ok()),
            namespace,
            convoy,
            vessel_ref: vessel,
            role,
        };
        Ok(flotilla_commands::Resolved::Ready(
            flotilla_protocol::Command::builder().action(flotilla_protocol::CommandAction::QueryMessageContacts { context }).build(),
        ))
    }
}

impl DomainCommand {
    pub fn resolve(self) -> Result<flotilla_commands::Resolved> {
        match self {
            DomainCommand::Repo(noun) => noun.resolve(),
            DomainCommand::Environment(noun) => noun.resolve(),
            DomainCommand::Checkout(noun) => noun.resolve(),
            DomainCommand::Convoy(noun) => noun.resolve(),
            DomainCommand::Dispatch(noun) => noun.resolve(),
            DomainCommand::Message(noun) => noun.resolve(),
            DomainCommand::Crew(noun) => noun.resolve_with_crew_id(std::env::var("FLOTILLA_CREW_ID").ok()),
            DomainCommand::Cr(noun) => noun.resolve(),
            DomainCommand::Issue(noun) => noun.resolve(),
            DomainCommand::Agent(noun) => noun.resolve(),
            DomainCommand::Host(partial) => {
                use flotilla_commands::Refinable;
                partial.refine().and_then(|noun| noun.resolve())
            }
            DomainCommand::Fulfilment(noun) => noun.resolve(),
            DomainCommand::WorkflowTemplate(noun) => noun.resolve(),
            DomainCommand::Project(noun) => noun.resolve(),
        }
        .map_err(|e| color_eyre::eyre::eyre!(e))
    }
}

#[derive(clap::Subcommand)]
pub enum ArtifactSubCommand {
    /// Store a crew artifact from a file the daemon can read
    #[command(
        long_about = "Store a crew artifact from a file path. The daemon reads the file; pass a path, not inline content.\n\nKinds: explainer (change explanation), decision-ledger (choices and alternatives), review-round (one review verdict), brief (handoff context), review-bundle (durable review evidence), recording, test-report, raw-test-output (bulky, short-retention evidence).\n\nPrefer Markdown for prose; self-contained HTML is also supported. --about names the exact subject, such as a commit or review round. --summary records small scalar facts for workflow conditions; keep detailed prose in the file."
    )]
    Put {
        #[arg(long)]
        kind: String,
        #[arg(long)]
        about: Option<String>,
        #[arg(long = "summary", value_parser = parse_artifact_summary)]
        summary: Vec<(String, serde_json::Value)>,
        file: PathBuf,
    },
    Get {
        reference: String,
        #[arg(short = 'o', long)]
        output: Option<PathBuf>,
    },
    List {
        #[arg(long)]
        convoy: Option<String>,
        #[arg(long)]
        kind: Option<String>,
        #[arg(long)]
        about: Option<String>,
    },
}

fn parse_artifact_summary(value: &str) -> Result<(String, serde_json::Value), String> {
    let (key, value) = value.split_once('=').ok_or_else(|| "summary must be key=value".to_string())?;
    if key.is_empty() {
        return Err("summary key must be nonempty".into());
    }
    let parsed = serde_json::from_str(value).unwrap_or_else(|_| serde_json::Value::String(value.to_string()));
    if !parsed.is_string() && !parsed.is_number() && !parsed.is_boolean() {
        return Err("summary value must be a string, number, or boolean".into());
    }
    Ok((key.to_string(), parsed))
}

